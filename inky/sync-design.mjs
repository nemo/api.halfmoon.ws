// Copy the design system from the inky-mirror repo into inky/design/.
// The design is authored and previewed in inky-mirror; this service renders it.
//   node inky/sync-design.mjs [path/to/inky-mirror]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(process.argv[2] || path.join(here, "../../inky-mirror"), "design");
const dst = path.join(here, "design");
if (!fs.existsSync(src)) { console.error(`no design at ${src}`); process.exit(1); }

fs.rmSync(dst, { recursive: true, force: true });
fs.mkdirSync(path.join(dst, "src"), { recursive: true });
fs.mkdirSync(path.join(dst, "fonts"), { recursive: true });
const copied = [];
for (const f of fs.readdirSync(path.join(src, "src"))) {
  if (!/\.(mjs|css)$/.test(f)) continue;
  fs.copyFileSync(path.join(src, "src", f), path.join(dst, "src", f)); copied.push(`src/${f}`);
}
for (const f of fs.readdirSync(path.join(src, "fonts"))) { fs.copyFileSync(path.join(src, "fonts", f), path.join(dst, "fonts", f)); copied.push(`fonts/${f}`); }
fs.copyFileSync(path.join(src, "quantise.mjs"), path.join(dst, "quantise.mjs")); copied.push("quantise.mjs");
// One self-contained stylesheet (tokens + base + components, font inlined) as
// a JS module, so serverless bundlers always ship it (no runtime fs paths).
const read = (f) => fs.readFileSync(path.join(dst, "src", f), "utf8").replace(/@import[^;]+;/g, "");
const font = fs.readFileSync(path.join(dst, "fonts", "Archivo-VF.ttf")).toString("base64");
const css = ["tokens.css", "base.css", "components.css"].map(read).join("\n")
  .replace(/url\(["']?\.\.\/fonts\/Archivo-VF\.ttf["']?\)/, `url(data:font/ttf;base64,${font})`);
if (!css.includes("data:font/ttf")) { console.error("font url not found in tokens.css"); process.exit(1); }
fs.writeFileSync(path.join(dst, "assets.mjs"), `// Generated by inky/sync-design.mjs. Do not edit.\nexport const CSS = ${JSON.stringify(css)};\n`);
copied.push("assets.mjs (generated)");
let rev = "unknown";
try { rev = fs.readFileSync(path.join(src, "..", ".git", "HEAD"), "utf8").trim(); } catch {}
fs.writeFileSync(path.join(dst, "SYNCED.md"),
  `Generated by \`node inky/sync-design.mjs\`. Do not edit here: edit inky-mirror/design and re-sync.\n\nSynced ${new Date().toISOString()} from ${src}\n\n${copied.map((c) => `- ${c}`).join("\n")}\n`);
console.log(`synced ${copied.length} files -> ${path.relative(process.cwd(), dst)}`);
